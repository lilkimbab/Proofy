"""Korean copy fixes for generated lecture content.

The curriculum builders in ``curriculum_seed`` produce scene text from templates.
This module is the single place that turns that template output into natural
Korean before it is shipped to the app:

* ``fix_josa`` resolves template particles such as ``미분은(는)`` → ``미분은``.
* ``SENTENCE_REWRITES`` replaces template sentences that repeat in every unit
  (keys are the exact builder output, values are the copy-edited text).
* ``polish_title`` renames generic scene titles to lecture-style chapter names.

``tests/test_lecture_copy.py`` checks that every key here still appears in the
builder output, so the table cannot silently drift from the templates.
"""

from __future__ import annotations

import re

_HANGUL_BASE = 0xAC00
_HANGUL_LAST = 0xD7A3
# Reading of the last character when it is not Hangul: digits by Korean reading,
# Latin letters by their usual English names (l, m, n, r end in a consonant).
_DIGIT_HAS_FINAL = {"0": True, "1": True, "2": False, "3": True, "4": False,
                    "5": False, "6": True, "7": True, "8": True, "9": False}
_DIGIT_FINAL_IS_RIEUL = {"1", "7", "8"}
_LATIN_HAS_FINAL = set("lmnrLMNR")


def _final_consonant(word: str) -> tuple[bool, bool]:
    """Return (has_final_consonant, final_is_rieul) for the last readable char."""
    for ch in reversed(word.strip()):
        code = ord(ch)
        if _HANGUL_BASE <= code <= _HANGUL_LAST:
            jong = (code - _HANGUL_BASE) % 28
            return jong != 0, jong == 8
        if ch in _DIGIT_HAS_FINAL:
            return _DIGIT_HAS_FINAL[ch], ch in _DIGIT_FINAL_IS_RIEUL
        if ch.isalpha():
            return ch in _LATIN_HAS_FINAL, ch in "lLrR"
        if ch in ")]}'\"’”":
            continue
        break
    return False, False


def josa(word: str, particle: str) -> str:
    """Attach the right form of a particle: josa("미분", "을") -> "미분을"."""
    has_final, is_rieul = _final_consonant(word)
    pairs = {
        "은": ("은", "는"), "는": ("은", "는"),
        "이": ("이", "가"), "가": ("이", "가"),
        "을": ("을", "를"), "를": ("을", "를"),
        "과": ("과", "와"), "와": ("과", "와"),
    }
    if particle in pairs:
        with_final, without_final = pairs[particle]
        return word + (with_final if has_final else without_final)
    if particle in ("으로", "로"):
        return word + ("으로" if has_final and not is_rieul else "로")
    raise ValueError(f"unsupported particle: {particle}")


_PAREN_JOSA = re.compile(
    r"(?P<word>[^\s(]+?)(?P<form>은\(는\)|는\(은\)|이\(가\)|가\(이\)|을\(를\)|를\(을\)|과\(와\)|와\(과\)|\(으\)로)"
)


def fix_josa(text: str) -> str:
    def _resolve(match: re.Match[str]) -> str:
        word, form = match.group("word"), match.group("form")
        particle = "으로" if form == "(으)로" else form[0]
        return josa(word, particle)

    return _PAREN_JOSA.sub(_resolve, text)


