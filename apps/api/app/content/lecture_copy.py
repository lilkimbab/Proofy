# "<개념> 오개념 교정" style titles generated per content element.
_TITLE_SUFFIX_REWRITES: list[tuple[str, str]] = [
    (" 오프닝", " 들어가며"),
    (" 오개념 교정", ": 자주 하는 실수"),
    (" 변형 예제 해설", ": 변형 문제"),
    (" 킬러 예제 해설", ": 킬러 예제"),
    (" 킬러 스킬", ": 고난도 전략"),
    (" 실전 연결", ": 실전 적용"),
    (" 핵심 설명", ": 핵심 개념"),
    (" 자세한 해설", ": 자세히 보기"),
]


def polish_title(title: str) -> str:
    if title in TITLE_REWRITES:
        return TITLE_REWRITES[title]
    for suffix, replacement in _TITLE_SUFFIX_REWRITES:
        if title.endswith(suffix):
            return fix_josa(title[: -len(suffix)] + replacement)
    return fix_josa(title)


def polish_text(text: str) -> str:
    return fix_josa(SENTENCE_REWRITES.get(text, text))


